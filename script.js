// Performance Optimizer
class PerformanceOptimizer {
    constructor() {
        this.initializeLazyLoading();
        this.initializeImageOptimization();
        this.preloadCriticalResources();
    }

    initializeLazyLoading() {
        if ('IntersectionObserver' in window) {
            const lazyImages = document.querySelectorAll('img[data-src]');
            const imageObserver = new IntersectionObserver((entries, observer) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        const img = entry.target;
                        img.src = img.dataset.src;
                        img.classList.remove('lazy');
                        imageObserver.unobserve(img);
                    }
                });
            });

            lazyImages.forEach(img => imageObserver.observe(img));
        }
    }

    initializeImageOptimization() {
        // Optimize image loading
        const images = document.querySelectorAll('img');
        images.forEach(img => {
            img.loading = 'lazy';
            img.decoding = 'async';
        });
    }

    preloadCriticalResources() {
        // Preload critical fonts
        const fontPreload = document.createElement('link');
        fontPreload.rel = 'preload';
        fontPreload.href = 'https://fonts.googleapis.com/css2?family=Cairo:wght@300;400;500;600;700;800&display=swap';
        fontPreload.as = 'style';
        document.head.appendChild(fontPreload);
    }
}

// Analytics and Error Tracking
class Analytics {
    constructor() {
        this.initializeErrorTracking();
        this.trackUserInteractions();
    }

    initializeErrorTracking() {
        window.addEventListener('error', (event) => {
            this.trackEvent('JavaScript Error', {
                message: event.message,
                filename: event.filename,
                lineno: event.lineno,
                colno: event.colno
            });
        });

        window.addEventListener('unhandledrejection', (event) => {
            this.trackEvent('Unhandled Promise Rejection', {
                reason: event.reason
            });
        });
    }

    trackUserInteractions() {
        // Track symptom searches
        const searchBtn = document.getElementById('searchBtn');
        if (searchBtn) {
            searchBtn.addEventListener('click', () => {
                const symptom = document.getElementById('symptomSelect').value;
                this.trackEvent('Symptom Search', { symptom });
            });
        }

        // Track cause detail views
        document.addEventListener('click', (e) => {
            if (e.target.closest('.cause-card')) {
                const causeTitle = e.target.closest('.cause-card').querySelector('.cause-title');
                if (causeTitle) {
                    this.trackEvent('Cause Detail View', { cause: causeTitle.textContent });
                }
            }
        });
    }

    trackEvent(eventName, data) {
        // In a real implementation, this would send data to analytics service
        console.log('Analytics Event:', eventName, data);
        
        // Example: Google Analytics 4
        if (typeof gtag !== 'undefined') {
            gtag('event', eventName, data);
        }
    }
}

